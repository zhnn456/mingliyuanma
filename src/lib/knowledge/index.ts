export function getArticleById(id: string): KnowledgeArticle | null {
  return KNOWLEDGE_ARTICLES.find(a => a.id === id) || null;
}

export function getArticlesByCategory(category: string): KnowledgeArticle[] {
  return KNOWLEDGE_ARTICLES.filter(a => a.category === category);
}

export function getArticlesByLevel(level: string): KnowledgeArticle[] {
  return KNOWLEDGE_ARTICLES.filter(a => a.level === level);
}

export function searchArticles(keyword: string): KnowledgeArticle[] {
  const kw = keyword.toLowerCase();
  return KNOWLEDGE_ARTICLES.filter(a =>
    a.title.toLowerCase().includes(kw) ||
    a.summary.toLowerCase().includes(kw) ||
    a.tags.some(t => t.toLowerCase().includes(kw))
  );
}
